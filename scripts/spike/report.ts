import { mkdirSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { SpikeArgs } from './args';
import type { Budget } from './budget';
import { ROOT_DIR, SPIKE_DIR, type SpikeEnv } from './env';
import { renderMarkdownTable, type Table } from './stats';
import type { ExperimentResult } from './types';

export function runOutputDir(label: string, startedAt: Date): string {
  const stamp = startedAt.toISOString().replace(/[:.]/g, '-');
  const dir = path.join(SPIKE_DIR, 'results', `${label}-${stamp}`);
  mkdirSync(dir, { recursive: true });
  return dir;
}

export function printTable(table: Table): void {
  console.log(`\n${renderMarkdownTable(table)}`);
}

function budgetTable(budget: Budget): Table {
  const rows = budget.breakdown().map((b) => [
    b.experiment,
    b.audioSeconds.toFixed(1),
    String(b.ttsChars),
    b.connectionSeconds.toFixed(0),
  ]);
  rows.push([
    'TOTAL',
    budget.audioSeconds.toFixed(1),
    String(budget.ttsChars),
    budget.connectionSeconds.toFixed(0),
  ]);
  return {
    title: 'Credit accounting (what this run sent, to compare with the Gnani dashboard)',
    headers: ['experiment', 'STT audio sent (s)', 'TTS characters', 'socket-open time (s)'],
    rows,
  };
}

/** Experiment F: print and return the spend table. */
export function accounting(budget: Budget): ExperimentResult {
  return {
    id: 'F',
    title: 'F. Credit accounting',
    tables: [budgetTable(budget)],
    notes: [
      `Limits for this run: ${budget.limits.maxAudioSeconds} s of audio, ${budget.limits.maxTtsChars} TTS characters.`,
      'Audio seconds count frames actually sent (32 ms each). Compare these totals with the dashboard before and after the run; how Gnani rounds or bills is not documented here.',
    ],
    data: budget.breakdown(),
    suggestions: [],
  };
}

export interface RunMeta {
  label: string;
  startedAt: string;
  mock: boolean;
  node: string;
  platform: string;
  args: SpikeArgs;
}

export function runMeta(args: SpikeArgs, env: SpikeEnv, startedAt: Date): RunMeta {
  return {
    label: args.label,
    startedAt: startedAt.toISOString(),
    mock: env.mock,
    node: process.version,
    platform: `${os.platform()} ${os.release()} ${os.arch()}`,
    args,
  };
}

export function writeResultsJson(outDir: string, meta: RunMeta, results: ExperimentResult[], budget: Budget): string {
  const file = path.join(outDir, 'results.json');
  writeFileSync(file, JSON.stringify({ meta, budget: budget.breakdown(), results }, null, 2));
  return file;
}

/**
 * Writes docs/LATENCY.md from MEASURED results. Refuses mock runs so fake numbers can never land in the
 * source-of-truth document. Decisions are suggestions: a human confirms them.
 */
export function writeLatencyDoc(meta: RunMeta, results: ExperimentResult[], budget: Budget, resultsFile: string): string {
  const file = path.join(ROOT_DIR, 'docs', 'LATENCY.md');
  const lines: string[] = [
    '# LATENCY.md: measured Gnani results',
    '',
    'Generated by `pnpm spike`. Every number below was measured in the run described here; nothing is estimated.',
    'Read this before changing STT or TTS parameters, and re-run the spike (with a new `--label`) after you change region or network.',
    '',
    '## Run',
    '',
    `- Label: \`${meta.label}\``,
    `- Started: ${meta.startedAt}`,
    `- Machine: ${meta.platform}, Node ${meta.node}`,
    `- Raw data: \`${path.relative(ROOT_DIR, resultsFile).replaceAll('\\', '/')}\` (git-ignored)`,
    `- Reproduce: \`pnpm spike --label ${meta.label}\`${meta.args.only ? ` --only ${meta.args.only.join(',')}` : ''} (needs GNANI_API_KEY and clips; spends credits)`,
    '',
    '## Decisions',
    '',
    'These are suggestions computed from the tables below with a simple rule (accuracy first, then speed). **A person must confirm each one**, and small samples can mislead. Once confirmed, copy the chosen values into `.env.example` and the gateway config.',
    '',
  ];
  const suggestions = results.filter((r) => r.suggestions.length > 0);
  if (suggestions.length === 0) lines.push('_No suggestions were produced by this run._', '');
  for (const result of suggestions) {
    lines.push(`**${result.title}**`, '', ...result.suggestions.map((s) => `- ${s}`), '');
  }

  for (const result of [...results, accounting(budget)]) {
    lines.push(`## ${result.title}`, '');
    for (const table of result.tables) lines.push(renderMarkdownTable(table));
    if (result.notes.length > 0) lines.push('Notes:', '', ...result.notes.map((n) => `- ${n}`), '');
  }
  writeFileSync(file, `${lines.join('\n')}\n`);
  return file;
}
