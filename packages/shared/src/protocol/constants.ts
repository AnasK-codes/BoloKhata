/** Protocol version carried in `hello` and `ready`. Bump on any breaking change. */
export const PROTOCOL_VERSION = 2;

/** Client microphone frames: 512 samples of 16-bit little-endian mono PCM at 16 kHz. */
export const AUDIO_SAMPLE_RATE = 16_000;
export const AUDIO_FRAME_SAMPLES = 512;
export const AUDIO_BYTES_PER_SAMPLE = 2;
export const AUDIO_FRAME_BYTES = AUDIO_FRAME_SAMPLES * AUDIO_BYTES_PER_SAMPLE; // 1,024
export const AUDIO_FRAME_MS = (AUDIO_FRAME_SAMPLES / AUDIO_SAMPLE_RATE) * 1000; // 32

/** TTS frames toward the browser: 1-byte type tag, 4-byte big-endian turn ID, then raw PCM. */
export const TTS_FRAME_TYPE = 0x01;
export const TTS_HEADER_BYTES = 5;
export const TTS_PCM_FORMAT = 'pcm_s16le';

/** Turn IDs are unsigned 32-bit integers, generated by the client. */
export const MAX_TURN_ID = 0xffff_ffff;

/** Size limits. Every message type has a cap so one bad client cannot exhaust memory. */
